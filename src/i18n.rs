/// Locales with a dedicated `/xx/` URL prefix. English is the default and is
/// served unprefixed at `/`.
pub const SUPPORTED_LOCALES: &[&str] = &["it", "de", "fr", "pt"];

pub fn is_supported_locale(lang: &str) -> bool {
    SUPPORTED_LOCALES.contains(&lang)
}

/// Normalizes any lang code to one we actually serve; unknown -> "en".
pub fn normalize(lang: &str) -> &'static str {
    match lang {
        "it" => "it",
        "de" => "de",
        "fr" => "fr",
        "pt" => "pt",
        _ => "en",
    }
}

/// `/it` for non-English, `""` for English (root, unprefixed).
pub fn prefix_for(lang: &str) -> String {
    if lang == "en" { String::new() } else { format!("/{lang}") }
}

/// Parses `Accept-Language` (RFC 7231 quality values) and returns the
/// highest-quality supported locale, if any. English is never returned here
/// (it's the implicit fallback when nothing matches).
pub fn best_supported_from_accept_language(header: &str) -> Option<&'static str> {
    let mut best: Option<(&'static str, f32)> = None;
    for part in header.split(',') {
        let part = part.trim();
        if part.is_empty() {
            continue;
        }
        let mut segs = part.split(';');
        let tag = segs.next().unwrap_or("").trim();
        let primary = tag.split('-').next().unwrap_or("").to_lowercase();
        if !is_supported_locale(&primary) {
            continue;
        }
        let mut q: f32 = 1.0;
        for seg in segs {
            let seg = seg.trim();
            if let Some(v) = seg.strip_prefix("q=") {
                q = v.trim().parse().unwrap_or(1.0);
            }
        }
        let code: &'static str = match primary.as_str() {
            "it" => "it",
            "de" => "de",
            "fr" => "fr",
            "pt" => "pt",
            _ => continue,
        };
        if best.map(|(_, bq)| q > bq).unwrap_or(true) {
            best = Some((code, q));
        }
    }
    best.map(|(code, _)| code)
}

